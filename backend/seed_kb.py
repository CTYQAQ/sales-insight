HANDBOOK = """# 销售分析口径手册

> 本手册定义平台内所有指标的计算口径与归属规则。任何数字上的争议，以本手册为准。

## 营收 Revenue

营收等于含税开票金额合计，不含运费、不含押金、不含代收代付。

归属月份按开票日期，不按合同签订日期，也不按收款日期。这是财务与销售最常对不上的地方：
销售同事习惯按签单月算业绩，但报表口径一律按开票月。

跨年订单如果分次开票，每一笔分别计入各自开票月份，不做整单归集。

## 成本 Cost

成本只统计直接采购成本，即商品的采购单价乘以数量。

以下三类不计入成本，它们进的是费用科目：仓储费、物流费、售后维修费。

这也是毛利率看起来比财务口径偏高的原因，回答相关问题时需要说明这一点。

## 毛利率 Gross Margin

毛利率等于营收减成本再除以营收，最后乘以百分之百。

如果该期间营收为零，毛利率返回空值而不是零，因为零会被误读成完全不赚钱。

毛利率低于百分之十五的产品线需要在月度经营会上单独说明原因。

## 退货 Return

退货金额在退货发生当月冲减营收。若退款跨月，以退货单审批日期为准，不看退款到账日期。

退货率等于退货金额除以当月营收，再乘以百分之百。

质量问题导致的退货要单独打标，它会从产品线的质量成本里再扣一次，
不要重复计算到销售口径里。

## 环比与同比

环比等于本期减上期再除以上期，是相邻两个统计周期的比较。月环比就是本月对上月。

同比等于本期减去年同期再除以去年同期。季节性强的品类必须看同比，环比会严重失真。

当上期为零时，环比返回空值，不返回无穷大，也不返回百分之一百。

## 区域划分

平台共划分为五个大区。

华东包含上海、江苏、浙江、安徽。

华北包含北京、天津、河北、山西、内蒙古。

华南包含广东、广西、福建、海南。

西南包含四川、重庆、云南、贵州。

华中包含湖北、湖南、河南、江西。

注意华中包含河南和江西。很多外部报表把江西算进华东，本平台不这样处理。

## 数据更新频率

事实表每日凌晨两点增量同步一次，因此当天的数据要到次日才能看到。

如果用户问今天的销售额，正确回答是数据尚未同步，最近可用日期为昨天。

## 权限与数据范围

区域经理只能看到自己所属大区的数据，总部角色可以看全量。

这是行级权限，在 SQL 层强制注入，不依赖前端过滤。
"""

FAQ = """# 常见问题与排查指南

## 报表数字和财务系统对不上怎么办

先确认三件事，九成的问题都在这三件事里。

第一是时间口径。平台按开票日期归月，财务可能按收款日期或签收日期。

第二是成本口径。平台只算直接采购成本，财务的全成本还含仓储物流和分摊费用。

第三是退货处理。平台在退货当月冲减营收，财务有时直接冲原单，导致两个月都变了。

确认完仍对不上，就导出明细表比对单号，差异通常是个别订单的归月错误。

## 为什么某个月的数据是空的

最常见原因是该月尚未同步。事实表每日凌晨两点增量同步，历史补数需要手工触发。

其次是区域权限。区域经理账号查别的区域，会返回空结果而不是报错。
这是有意的设计，避免通过报错探测其他区域是否存在数据。

## 上传 Excel 后数据显示不全

检查三件事：表头是否在第一行、日期列是否被 Excel 存成了文本、
金额列有没有混入千分位逗号。

千分位逗号是最高频的问题。带逗号的金额会被解析成字符串，聚合时静默变成零，
而且不会报错，非常难排查。

## AI 生成的查询结果不对

AI 只负责把自然语言翻译成 SQL 并解读查询结果，所有数字都来自本地数据库的真实查询，
不会编造数据。

如果结果不对，请检查问题里的时间范围和维度名称是否与实际数据一致。

常见误用有两个：说上个月但系统当前没有该月数据；说华东区而实际区域名是华东。

## 告警没有收到

告警有三道闸门：阈值判断、去重窗口、通知渠道配置。

去重窗口默认六十分钟，同一指标同一维度在窗口内只发一次，
这是为了避免大盘抖动时刷屏。

如果确认配置正确仍收不到，检查 webhook 的机器人是否还在群里、是否被限流。

## 能不能对接我们的 MySQL

可以。平台支持 SQLite、MySQL、PostgreSQL 三种数据源，改一个连接串即可。

注意 AI 问数功能依赖表结构白名单。接入新库需要在配置里登记允许查询的表，
未登记的表会被安全围栏直接拒绝。
"""

OPS = """# 部署与运维手册

## 本地启动

后端进入 backend 目录，激活虚拟环境后执行 python run.py，默认监听 8000 端口。

前端进入 frontend 目录执行 npm run dev，默认监听 5173 端口，已配置代理到 8000。

两者都要起，否则前端会报接口错误。

## 环境变量改动为什么不生效

配置是启动时一次性加载并缓存的，改了 .env 必须重启后端进程。

开发模式的自动重载只监听 Python 文件，改 .env 不会触发重载。
这是排查配置问题时的第一个坑。

## 数据库迁移

切换到 MySQL 或 PostgreSQL 只需要改 DATABASE_URL 一个值，业务代码无需改动。

首次启动会自动建表。已有 SQLite 数据要迁过去，需要单独写导出导入脚本。

## 向量库选择

默认使用 Milvus 的 lite 模式，数据落在本地文件，不需要 Docker。

数据量超过百万级或者需要多实例共享时，改用 standalone 模式，
把连接串改成 HTTP 地址并启动 Milvus 容器即可，业务代码不用改。

## 换 Embedding 模型后检索变空

这是因为集合名里带了模型指纹，换模型等于换了一个新集合。

正确做法是换完模型后重建索引，把已知文档重新灌一遍。
旧集合可以保留也可以删掉，不会影响新模型。

## 日志与排查

后端日志带 request_id，前端报错弹窗里也能拿到同一个 id，按 id 搜日志即可定位。

常见 503 是外部依赖不可用，比如大模型接口超时或向量库没启动。
常见 401 是密钥失效，不是网络问题，重试没有意义。
"""

